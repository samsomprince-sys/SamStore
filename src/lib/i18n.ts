export type Language = 'ar' | 'fr' | 'en';

const KEY = 'dz_lang';

export function getStoredLang(): Language {
  try {
    const v = localStorage.getItem(KEY);
    return v === 'fr' || v === 'en' || v === 'ar' ? v : 'ar';
  } catch {
    return 'ar';
  }
}

export function setStoredLang(l: Language) {
  try {
    localStorage.setItem(KEY, l);
  } catch {
    /* ignore */
  }
}

